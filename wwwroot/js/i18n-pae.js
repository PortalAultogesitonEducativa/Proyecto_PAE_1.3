    // Índice en minúsculas para capturar textos en MAYÚSCULAS (ej: "ACTIVA" -> "ACTIVE")
    const DICCIONARIO_EN_LOWER = {};
    Object.keys(DICCIONARIO_EN).forEach(k => {
        DICCIONARIO_EN_LOWER[k.toLowerCase()] = DICCIONARIO_EN[k];
    });

    function aplicarCapitalizacion(original, traducido) {
        if (original === original.toUpperCase() && original !== original.toLowerCase()) {
            return traducido.toUpperCase();
        }
        return traducido;
    }

    // ======================================================================
    // MOTOR DE TRADUCCIÓN DE TEXTO Y PATRONES DINÁMICOS
    // ======================================================================
    function traducirTexto(textoOriginal) {
        if (!textoOriginal || typeof textoOriginal !== 'string') return textoOriginal;

        const matchEspacios = textoOriginal.match(/^(\s*)([\s\S]*?)(\s*)$/);
        if (!matchEspacios) return textoOriginal;

        const leading = matchEspacios[1];
        const cuerpo = matchEspacios[2];
        const trailing = matchEspacios[3];

        const limpio = cuerpo.replace(/\s+/g, ' ').trim();
        if (!limpio || limpio.length < 2) return textoOriginal;

        // 1. Búsqueda directa exacta en el diccionario
        if (DICCIONARIO_EN[limpio]) {
            return leading + DICCIONARIO_EN[limpio] + trailing;
        }

        // 2. Búsqueda insensible a mayúsculas (ej. "ACTIVA", "FINALIZADA", "GRADO / CURSO")
        const lowerKey = limpio.toLowerCase();
        if (DICCIONARIO_EN_LOWER[lowerKey]) {
            return leading + aplicarCapitalizacion(limpio, DICCIONARIO_EN_LOWER[lowerKey]) + trailing;
        }

        // 3. Patrones dinámicos (Años, Cursos, Prerrequisitos, Grados, Períodos y Alertas)
        let tr = null;

        const mMatriculasAnio = limpio.match(/^Matr[íi]culas\s+(\d{4})$/i);
        if (mMatriculasAnio) tr = `Enrollments ${mMatriculasAnio[1]}`;

        const mRenovarAnio = limpio.match(/^Renovar\s+Matr[íi]cula\s+(\d{4})$/i);
        if (mRenovarAnio) tr = `Renew Enrollment ${mRenovarAnio[1]}`;

        const mCursoPrefijo = limpio.match(/^Curso:\s*(.+)$/i);
        if (mCursoPrefijo) tr = `Course: ${mCursoPrefijo[1]}`;

        const mCursoNum = limpio.match(/^Curso\s+([A-Za-z0-9\-]+)$/i);
        if (mCursoNum) tr = `Course ${mCursoNum[1]}`;

        const mPrerreqGrado = limpio.match(/^Prerrequisito:\s*Grado\s+(\d+)°?$/i);
        if (mPrerreqGrado) tr = `Prerequisite: Grade ${mPrerreqGrado[1]}`;

        const mPrerreqGen = limpio.match(/^Prerrequisito:\s*(.+)$/i);
        if (mPrerreqGen) tr = `Prerequisite: ${mPrerreqGen[1]}`;

        const mMostrando = limpio.match(/^Mostrando\s+(\d+)\s+registros$/i);
        if (mMostrando) tr = `Showing ${mMostrando[1]} record(s)`;

        const mMostrandoDe = limpio.match(/^Mostrando\s+(\d+)\s+de\s+(\d+)\s+registros$/i);
        if (mMostrandoDe) tr = `Showing ${mMostrandoDe[1]} of ${mMostrandoDe[2]} records`;

        const mGrado1 = limpio.match(/^Grado\s+(\d+)°?$/i);
        if (mGrado1) tr = `Grade ${mGrado1[1]}`;

        const mGrado2 = limpio.match(/^(\d+)°?\s+Grado$/i);
        if (mGrado2) tr = `Grade ${mGrado2[1]}`;

        const mPeriodo = limpio.match(/^Per[íi]odo\s+(\d+)(\s*Cerrado)?$/i);
        if (mPeriodo) tr = `Term mPeriodo[1]{mPeriodo[2] ? ' (Closed)' : ''}`;

        const mPeriodoActivo = limpio.match(/^Periodo\s+Activo:\s*P(\d+)$/i);
        if (mPeriodoActivo) tr = `Active Term: T${mPeriodoActivo[1]}`;

        const mPromedio = limpio.match(/^Promedio:\s*(.+)$/i);
        if (mPromedio) tr = `Average: ${mPromedio[1]}`;

        const mDocentePref = limpio.match(/^Docente:\s*(.+)$/i);
        if (mDocentePref) tr = `Teacher: ${mDocentePref[1]}`;

        const mAccionMejora = limpio.match(/^Acci[óo]n\s+de\s+Mejora:\s*(.+)\s+\(P(\d+)\)$/i);
        if (mAccionMejora) tr = `Improvement Action: mAccionMejora[1](T{mAccionMejora[2]})`;

        const mInscritos = limpio.match(/^Estudiantes Inscritos\s*\((\d+)\)$/i);
        if (mInscritos) tr = `Enrolled Students (${mInscritos[1]})`;

        const mTodosEst = limpio.match(/^Todos los estudiantes\s*\((\d+)\)$/i);
        if (mTodosEst) tr = `All students (${mTodosEst[1]})`;

        const mCantEst = limpio.match(/^(\d+)\s+Estudiantes$/i);
        if (mCantEst) tr = `${mCantEst[1]} Students`;

        const mTotalAsist = limpio.match(/^Total asistencias registradas:\s*(\d+)\s*\((\d+)\s*registros de presencia\)\.$/i);
        if (mTotalAsist) tr = `Total attendance recorded: mTotalAsist[1]({mTotalAsist[2]} presence records).`;

        const mMatRetiradas = limpio.match(/^Matr[íi]culas retiradas o inactivas:\s*(\d+)\s*de\s*(\d+)\s*matr[íi]culas procesadas\.$/i);
        if (mMatRetiradas) tr = `Withdrawn or inactive enrollments: ${mMatRetiradas[1]} of ${mMatRetiradas[2]} processed enrollments.`;

        const mCopyright = limpio.match(/^(?:©|&copy;)\s*(\d{4})\s*Portal de Autogesti[óo]n Educativa - PAE\.\s*Todos los derechos reservados\.$/i);
        if (mCopyright) tr = `© ${mCopyright[1]} Educational Self-Management Portal - PAE. All rights reserved.`;

        const mGuardarNotas = limpio.match(/^Se guardarán las calificaciones de (\d+) estudiantes en (.+?) \((.+?) - Per[íi]odo (\d+)\)\.$/i);
        if (mGuardarNotas) {
            tr = `Grades will be saved for ${mGuardarNotas[1]} student(s) in mGuardarNotas[2]({mGuardarNotas[3]} - Term ${mGuardarNotas[4]}).`;
        }

        const mConfPeriodo = limpio.match(/^¿Confirmar cambio en Per[íi]odo (\d+)\?$/i);
        if (mConfPeriodo) tr = `Confirm change in Term ${mConfPeriodo[1]}?`;

        const mRecPeriodo = limpio.match(/^¿Emitir recordatorio de Per[íi]odo (\d+)\?$/i);
        if (mRecPeriodo) tr = `Send reminder for Term ${mRecPeriodo[1]}?`;

        const mDocsReq = limpio.match(/^Debes adjuntar todos los documentos requeridos antes de poder enviar tu postulación\. Actualmente has cargado (\d+) de (\d+) documentos\.$/i);
        if (mDocsReq) {
            tr = `You must attach all required documents before submitting your application. You have currently uploaded ${mDocsReq[1]} of ${mDocsReq[2]} documents.`;
        }

        const mNotaGuardada = limpio.match(/^Nota guardada en planilla:\s*(.+)$/i);
        if (mNotaGuardada) tr = `Grade saved in gradebook: ${mNotaGuardada[1]}`;

        const mConfInscripcion = limpio.match(/^¿Confirma su inscripción al curso (.+?)\?$/i);
        if (mConfInscripcion) tr = `Confirm your enrollment in the course ${mConfInscripcion[1]}?`;

        const mCancelInscripcion = limpio.match(/^¿Está seguro de cancelar su inscripción a (.+?)\? Su cupo será liberado\.$/i);
        if (mCancelInscripcion) tr = `Are you sure you want to cancel your enrollment in ${mCancelInscripcion[1]}? Your spot will be released.`;

        const mEliminarElem = limpio.match(/^¿Está seguro de eliminar (.+?)\?$/i);
        if (mEliminarElem) tr = `Are you sure you want to delete ${mEliminarElem[1]}?`;

        if (tr) {
            return leading + aplicarCapitalizacion(limpio, tr) + trailing;
        }

        return textoOriginal;
    }

