    function traducirHtmlFragmento(htmlStr) {
        if (!htmlStr || typeof htmlStr !== 'string') return htmlStr;
        const temp = document.createElement('div');
        temp.innerHTML = htmlStr;
        traducirNodo(temp);
        return temp.innerHTML;
    }

    if (typeof Swal !== 'undefined' && typeof Swal.fire === 'function') {
        const originalSwalFire = Swal.fire.bind(Swal);
        Swal.fire = function (...args) {
            if (args.length === 1 && typeof args[0] === 'object' && args[0] !== null) {
                const opts = Object.assign({}, args[0]);
                if (typeof opts.title === 'string') opts.title = traducirTexto(opts.title);
                if (typeof opts.text === 'string') opts.text = traducirTexto(opts.text);
                if (typeof opts.html === 'string') opts.html = traducirHtmlFragmento(opts.html);
                if (typeof opts.confirmButtonText === 'string') opts.confirmButtonText = traducirHtmlFragmento(opts.confirmButtonText);
                if (typeof opts.cancelButtonText === 'string') opts.cancelButtonText = traducirHtmlFragmento(opts.cancelButtonText);
                return originalSwalFire(opts);
            } else if (args.length >= 1) {
                const translatedArgs = args.map(a => typeof a === 'string' ? traducirTexto(a) : a);
                return originalSwalFire(...translatedArgs);
            }
            return originalSwalFire(...args);
        };
    }

    // ======================================================================
    // TRADUCCIÓN DEL DOM Y OBSERVADOR DE CAMBIOS DINÁMICOS
    // ======================================================================
    function traducirNodo(root) {
        if (!root) return;

        const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
            acceptNode: function (node) {
                const parent = node.parentElement;
                if (!parent) return NodeFilter.FILTER_REJECT;
                const tag = parent.tagName;
                if (tag === 'SCRIPT' || tag === 'STYLE' || tag === 'TEXTAREA' || parent.closest('[data-no-i18n]')) {
                    return NodeFilter.FILTER_REJECT;
                }
                return NodeFilter.FILTER_ACCEPT;
            }
        });

        let nodoTexto;
        while ((nodoTexto = walker.nextNode())) {
            const actual = nodoTexto.nodeValue;
            const traducido = traducirTexto(actual);
            if (traducido !== actual) {
                nodoTexto.nodeValue = traducido;
            }
        }

        if (root.querySelectorAll) {
            root.querySelectorAll('[placeholder], [title], input[type="submit"], input[type="button"]').forEach(el => {
                if (el.closest('[data-no-i18n]')) return;
                if (el.hasAttribute('placeholder')) {
                    const ph = el.getAttribute('placeholder');
                    const phTr = traducirTexto(ph);
                    if (phTr !== ph) el.setAttribute('placeholder', phTr);
                }
                if (el.hasAttribute('title')) {
                    const ti = el.getAttribute('title');
                    const tiTr = traducirTexto(ti);
                    if (tiTr !== ti) el.setAttribute('title', tiTr);
                }
                if (el.tagName === 'INPUT' && (el.type === 'submit' || el.type === 'button') && el.value) {
                    const valTr = traducirTexto(el.value);
                    if (valTr !== el.value) el.value = valTr;
                }
            });
        }
    }

    document.addEventListener('DOMContentLoaded', function () {
        traducirNodo(document.body);

        const observer = new MutationObserver(function (mutations) {
            mutations.forEach(function (mutation) {
                mutation.addedNodes.forEach(function (node) {
                    if (node.nodeType === Node.ELEMENT_NODE) {
                        traducirNodo(node);
                    } else if (node.nodeType === Node.TEXT_NODE && node.parentElement) {
                        const nuevo = traducirTexto(node.nodeValue);
                        if (nuevo !== node.nodeValue) node.nodeValue = nuevo;
                    }
                });
            });
        });

        observer.observe(document.body, { childList: true, subtree: true });
    });
